/**
 * PostgreSQL access layer.
 *
 * - Production (Google Cloud SQL): set DATABASE_URL, uses the `pg` driver.
 * - Local development & tests: no DATABASE_URL → embedded PostgreSQL (PGlite),
 *   stored in PGLITE_DIR (default ./data/pglite) or in memory with ':memory:'.
 *
 * SQL is written with `?` placeholders; they are converted to $1, $2… here.
 * DATE columns are returned as 'YYYY-MM-DD' strings (no timezone shifts).
 */
import fs from 'node:fs';
import path from 'node:path';

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','owner','admin')),
  prefs JSONB NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS businesses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER REFERENCES users(id),
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  cuisine TEXT NOT NULL,
  city TEXT NOT NULL,
  address TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  price_level INTEGER NOT NULL DEFAULT 2 CHECK (price_level BETWEEN 1 AND 4),
  tags JSONB NOT NULL DEFAULT '[]',
  specialties JSONB NOT NULL DEFAULT '[]',
  opening_hours TEXT NOT NULL DEFAULT '',
  accepts_reservations BOOLEAN NOT NULL DEFAULT true,
  qr_code TEXT NOT NULL UNIQUE,
  contract_status TEXT NOT NULL DEFAULT 'active' CHECK (contract_status IN ('pending','active','suspended')),
  subscription_until DATE NOT NULL,
  inspected_at DATE,
  inspected_by TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_business_geo ON businesses(lat, lng);
-- Google Maps place ID of a contracted business (the only Google data we keep).
ALTER TABLE businesses ADD COLUMN IF NOT EXISTS google_place_id TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS idx_business_google ON businesses(google_place_id);

CREATE TABLE IF NOT EXISTS products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  city TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS visits (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  business_id INTEGER NOT NULL REFERENCES businesses(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_visits_user ON visits(user_id);

CREATE TABLE IF NOT EXISTS ratings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  business_id INTEGER NOT NULL REFERENCES businesses(id),
  visit_id INTEGER NOT NULL UNIQUE REFERENCES visits(id),
  score INTEGER NOT NULL CHECK (score BETWEEN 1 AND 5),
  taste INTEGER CHECK (taste BETWEEN 1 AND 5),
  hygiene INTEGER CHECK (hygiene BETWEEN 1 AND 5),
  value INTEGER CHECK (value BETWEEN 1 AND 5),
  comment TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ratings_business ON ratings(business_id);
CREATE INDEX IF NOT EXISTS idx_ratings_user ON ratings(user_id);

CREATE TABLE IF NOT EXISTS points_ledger (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  points INTEGER NOT NULL,
  reason TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_points_user ON points_ledger(user_id);

CREATE TABLE IF NOT EXISTS reservations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  business_id INTEGER NOT NULL REFERENCES businesses(id),
  reserved_for TIMESTAMPTZ NOT NULL,
  party_size INTEGER NOT NULL CHECK (party_size BETWEEN 1 AND 50),
  note TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','rejected','cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS campaigns (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sponsor_type TEXT NOT NULL CHECK (sponsor_type IN ('isletme','belediye','uretici')),
  sponsor_name TEXT NOT NULL,
  title TEXT NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  city TEXT,
  business_id INTEGER REFERENCES businesses(id),
  starts_at DATE NOT NULL,
  ends_at DATE NOT NULL
);
`;

const DATE_OID = 1082;

/** Converts `?` placeholders to PostgreSQL's $1, $2, … */
function toPg(sql) {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
}

class Db {
  /** @param {(sql: string, params: unknown[]) => Promise<{ rows: any[], rowCount: number }>} query */
  constructor(query, transaction, close) {
    this._query = query;
    this._transaction = transaction;
    this.close = close;
  }
  async all(sql, ...params) {
    return (await this._query(toPg(sql), params)).rows;
  }
  async get(sql, ...params) {
    return (await this._query(toPg(sql), params)).rows[0];
  }
  /** Returns the number of affected rows. */
  async run(sql, ...params) {
    return (await this._query(toPg(sql), params)).rowCount;
  }
  /** INSERT … and return the new row's id. */
  async insert(sql, ...params) {
    return Number((await this._query(toPg(`${sql} RETURNING id`), params)).rows[0].id);
  }
  /** Runs fn(txDb) in a transaction; rolls back if it throws. */
  tx(fn) {
    return this._transaction(fn);
  }
}

async function pgliteDb(dir) {
  const { PGlite } = await import('@electric-sql/pglite');
  if (dir !== ':memory:') fs.mkdirSync(dir, { recursive: true });
  const pg = new PGlite(dir === ':memory:' ? undefined : dir, { parsers: { [DATE_OID]: (v) => v } });
  const wrap = (q) => async (sql, params) => {
    const r = await q.query(sql, params);
    return { rows: r.rows, rowCount: r.affectedRows ?? 0 };
  };
  const db = new Db(wrap(pg), (fn) => pg.transaction((tx) => fn(new Db(wrap(tx), () => { throw new Error('Nested transaction'); }))), () => pg.close());
  await pg.exec(SCHEMA);
  return db;
}

async function postgresDb(url) {
  const { default: pg } = await import('pg');
  pg.types.setTypeParser(DATE_OID, (v) => v);
  const pool = new pg.Pool({ connectionString: url, max: Number(process.env.DB_POOL_SIZE || 5) });
  const wrap = (c) => async (sql, params) => {
    const r = await c.query(sql, params);
    return { rows: r.rows, rowCount: r.rowCount ?? 0 };
  };
  const transaction = async (fn) => {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await fn(new Db(wrap(client), () => { throw new Error('Nested transaction'); }));
      await client.query('COMMIT');
      return result;
    } catch (e) {
      await client.query('ROLLBACK');
      throw e;
    } finally {
      client.release();
    }
  };
  const db = new Db(wrap(pool), transaction, () => pool.end());
  await pool.query(SCHEMA);
  return db;
}

/**
 * Opens the database and makes sure the schema exists.
 * @param {string} [target] a postgres:// URL, a PGlite directory, or ':memory:'
 */
export function openDb(target = process.env.DATABASE_URL || process.env.PGLITE_DIR || path.resolve('data/pglite')) {
  return /^postgres(ql)?:\/\//.test(target) ? postgresDb(target) : pgliteDb(target);
}
